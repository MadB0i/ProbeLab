/*
 * Fails when the generated icons no longer match `src-tauri/app-icon.svg`.
 *
 * # Why this exists
 *
 * `app-icon.svg` used to be referenced by nothing at all -- no script, no config, no test. It was a
 * hand-authored file that looked like the icon source and was not one, so editing it changed nothing
 * a user would ever see. The real icons were a frozen `tauri icon` output from months earlier. Anyone
 * who opened the SVG reasonably assumed they were editing the app icon.
 *
 * The fix was to make the SVG a real source (`pnpm icons` regenerates every platform size from it), and
 * this is the guard that keeps it one. Without it, the file can quietly stop being the source again --
 * someone regenerates icons by hand, or commits a new PNG, and the SVG drifts back into a dead file
 * that looks authoritative.
 *
 * # How it checks
 *
 * Rasterising the SVG and comparing bytes is not possible here without the native toolchain that
 * `tauri icon` needs, so instead this hashes the source and the outputs and compares the hash *of the
 * SVG* recorded in a manifest that `pnpm icons` writes. Regenerating rewrites the manifest; editing the
 * SVG without regenerating leaves it stale. That catches the real failure -- "the mark was changed but
 * the icons were not" -- without depending on rasteriser output being byte-stable across machines.
 */
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const SOURCE = join(HERE, "..", "src-tauri", "app-icon.svg");
const MANIFEST = join(HERE, "..", "src-tauri", "icons", "source-manifest.json");
const WRITING = process.argv.includes("--write");

function sha256(path) {
  return createHash("sha256").update(readFileSync(path)).digest("hex");
}

if (!existsSync(SOURCE)) {
  console.error(`the icon source ${SOURCE} is missing`);
  process.exit(1);
}

const source = sha256(SOURCE);

// The outputs that must exist for the app to build and to look like itself. `tauri.conf.json` lists a
// subset; the rest are what the Windows and Store builds read, and a missing one fails at packaging
// time on a maintainer's machine rather than in CI.
const REQUIRED = [
  "32x32.png",
  "128x128.png",
  "128x128@2x.png",
  "icon.png",
  "icon.ico",
  "icon.icns",
  "Square44x44Logo.png",
  "Square150x150Logo.png",
  "StoreLogo.png",
];

if (WRITING) {
  const outputs = Object.fromEntries(REQUIRED.map((name) => [name, sha256(join(HERE, "..", "src-tauri", "icons", name))]));
  writeFileSync(MANIFEST, `${JSON.stringify({ source, outputs }, null, 2)}\n`);
  console.log(`icon manifest: ${MANIFEST}`);
  process.exit(0);
}

if (!existsSync(MANIFEST)) {
  console.error(
    `${MANIFEST} is missing, so the icons cannot be traced to a source. ` +
      "Run `pnpm icons` to regenerate, which also records the manifest.",
  );
  process.exit(1);
}

const manifest = JSON.parse(readFileSync(MANIFEST, "utf8"));
const problems = [];

if (manifest.source !== source) {
  problems.push(
    "app-icon.svg has changed since the icons were generated. Run `pnpm icons` to propagate the " +
      "mark, then `pnpm check:icons --write`.",
  );
}

for (const name of REQUIRED) {
  const path = join(HERE, "..", "src-tauri", "icons", name);
  if (!existsSync(path)) {
    problems.push(`${name} is missing. Run \`pnpm icons\`.`);
    continue;
  }
  const recorded = manifest.outputs?.[name];
  if (recorded === undefined) {
    problems.push(`${name} is not in the manifest. Run \`pnpm check:icons --write\`.`);
  } else if (recorded !== sha256(path)) {
    problems.push(`${name} does not match the manifest. It was edited or regenerated by hand; run \`pnpm icons\`.`);
  }
}

if (problems.length > 0) {
  console.error("The app icons are not the current render of app-icon.svg:\n");
  for (const problem of problems) console.error(`  - ${problem}`);
  process.exit(1);
}

console.log(`icons: OK, ${REQUIRED.length} outputs match app-icon.svg (${source.slice(0, 12)}).`);
