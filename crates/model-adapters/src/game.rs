//! The game protocol: how a model is told a board, and how a reply is read back.
//!
//! # Why this is a second protocol rather than a reuse of the grid one
//!
//! The grid protocol in this crate's root maps five literal names to five grid actions and validates
//! the choice against an `available_actions` list. A game board has no position, no neighbours, and
//! no Manhattan distance, and its legal moves are not a fixed vocabulary: for connect four the legal
//! set is whichever columns are not yet full, so it changes every ply. Folding games into the grid
//! parser would mean either widening the grid vocabulary — which every grid environment would then
//! have to advertise and defend — or special-casing tokens inside a parser whose whole job is
//! mapping a name to a grid `Action`. Both were rejected.
//!
//! # What the model is shown, and what it is not
//!
//! The user message carries exactly the fields of [`probelab_core::GameRequest`]: the board as *this
//! side* sees it, the legal move list for this ply, this side's own bounded history, and the ply
//! counters. It carries nothing else. In particular:
//!
//! - no evaluator internals, no scoring function, no search depth, no opponent policy;
//! - no seed, and no information beyond what the game's own `view` produced.
//!
//! That last point is load-bearing rather than cosmetic. The board a model sees is generated by
//! `Game::view`, and the only information leaving a game state is what that method returns. A model
//! cannot be shown a hidden cell, because no hidden cell exists in the value being serialized.
//!
//! # Why the board is rendered twice
//!
//! Every game request carries the board as JSON *and* an ASCII rendering. The JSON is the precise
//! representation and the one the parser and the validator use. The ASCII is what small local models
//! actually read reliably: a 3x3 or 7x6 grid of labelled cells is a spatial pattern that language
//! models handle far better than nested array indexing, and connect four in particular is a game
//! about column heights, which `[[...],[...]]` communicates far worse than a picture of stacked discs.
//!
//! Rendering twice cannot desynchronize the two, because both are derived from the same
//! `GameBoard` value in the same function. The renderer is not a source of truth; it is a second
//! projection of one.
//!
//! # Strictness
//!
//! Parsing reuses the grid protocol's tolerance rules exactly — prose and code fences around one JSON
//! object are fine, a second JSON value is not — and adds two game-specific refusals: an unknown game
//! tag, and a move outside the legal set the request actually offered. Both are checked against the
//! request, never against a hard-coded list, so a move the engine would refuse is refused here first
//! with a typed reason.

use probelab_core::{
    GameBoard, GameKind, GameMove, GameRequest, GameSide, TicTacToeCell, GAME_HISTORY_WINDOW,
};
use serde::Serialize;

use crate::ActionProtocolError;

/// The prompt template version for tic-tac-toe.
pub const TIC_TAC_TOE_PROMPT_TEMPLATE_VERSION: &str = "tic_tac_toe_v1";
/// The prompt template version for connect four.
pub const CONNECT_FOUR_PROMPT_TEMPLATE_VERSION: &str = "connect_four_v1";

const TIC_TAC_TOE_PROMPT: &str = include_str!("../../../prompts/tic_tac_toe_v1.md");
const CONNECT_FOUR_PROMPT: &str = include_str!("../../../prompts/connect_four_v1.md");

/// The system prompt and its version for one game.
pub fn prompt_for(kind: GameKind) -> (&'static str, &'static str) {
    match kind {
        GameKind::TicTacToe => (TIC_TAC_TOE_PROMPT, TIC_TAC_TOE_PROMPT_TEMPLATE_VERSION),
        GameKind::ConnectFour => (CONNECT_FOUR_PROMPT, CONNECT_FOUR_PROMPT_TEMPLATE_VERSION),
        // The arena refuses these before a request is ever built, so no prompt exists for them.
        // Returning the tic-tac-toe template would be a lie about which rules the model was given.
        GameKind::Rps | GameKind::Battleship => (TIC_TAC_TOE_PROMPT, "unsupported_game_v0"),
    }
}

/// The prompt template version for one game.
pub fn prompt_template_version(kind: GameKind) -> &'static str {
    prompt_for(kind).1
}

/// The stable name for a legal game move, as it appears in the prompt vocabulary.
///
/// Strings rather than numbers, deliberately, for the same reason the grid protocol uses
/// `MOVE_UP` rather than `0`: a named token is one a model can reproduce exactly, and the name is
/// self-describing in a transcript.
///
/// **One-based, for every game.** `CELL_1` and `COLUMN_1` are both the first cell and the first
/// column, because a model that counts from one and a model that counts from zero must not produce
/// different moves for the same cell — and because a prompt whose first named option is `CELL_0`
/// reads like an off-by-one bug to a careful reader. The index on [`GameMove`] stays zero-based,
/// which is what every array in this codebase uses; only the wire vocabulary is one-based, and the
/// parser converts.
pub fn protocol_move_name(kind: GameKind, index: usize) -> String {
    match kind {
        GameKind::ConnectFour => format!("COLUMN_{}", index + 1),
        GameKind::TicTacToe => format!("CELL_{}", index + 1),
        GameKind::Rps => format!("PLAY_{}", index + 1),
        GameKind::Battleship => format!("TARGET_{}", index + 1),
    }
}

/// The board, rendered as text for the prompt.
fn render_board(board: &GameBoard) -> String {
    match board {
        GameBoard::TicTacToe { cells } => render_tictactoe(cells),
        GameBoard::ConnectFour {
            columns,
            rows,
            cells,
        } => render_connect_four(*columns, *rows, cells),
        // Never reached: `prompt_for` has no template for these, so no request is built for them.
        other => format!("{other:?}"),
    }
}

fn render_tictactoe(cells: &[TicTacToeCell]) -> String {
    let mut out = String::new();
    for row in 0..3usize {
        if row > 0 {
            out.push('\n');
        }
        out.push_str("  ");
        for column in 0..3usize {
            if column > 0 {
                out.push_str(" | ");
            }
            let glyph = match cells.get(row * 3 + column) {
                Some(TicTacToeCell::First) => " X ",
                Some(TicTacToeCell::Second) => " O ",
                _ => " . ",
            };
            out.push_str(glyph);
        }
        out.push_str(&format!("   row {}", row + 1));
    }
    out
}

/// Renders connect four with row 1 at the bottom, matching how the board is described in words.
///
/// The core schema stores cells column-major, so a row here is a stride walk over `cells`. That is
/// the one place the two representations meet, and it is a single expression in a single function:
/// `cells[column * rows + row]` for the cell at `row` from the bottom of `column`. The prompt
/// renderer and the engine's rule code therefore cannot disagree about where a disc landed, because
/// they read the same index.
fn render_connect_four(
    columns: usize,
    rows: usize,
    cells: &[probelab_core::ConnectFourCell],
) -> String {
    let mut out = String::new();
    // Top row first, so row 1 — the bottom, the row gravity fills first — reads last.
    for row in (0..rows).rev() {
        out.push_str("  ");
        for column in 0..columns {
            if column > 0 {
                out.push(' ');
            }
            let glyph = match cells.get(column * rows + row) {
                Some(probelab_core::ConnectFourCell::First) => " O ",
                Some(probelab_core::ConnectFourCell::Second) => " X ",
                Some(_) => " . ",
                // An out-of-range index is a board the caller got wrong, not an empty cell. `?` makes
                // that visible in the prompt instead of rendering as a playable space.
                None => " ? ",
            };
            out.push_str(glyph);
        }
        if row == 0 {
            out.push_str("   row 1 (bottom)");
        } else {
            out.push_str(&format!("   row {}", row + 1));
        }
        out.push('\n');
    }
    out.push_str("  ");
    for column in 0..columns {
        if column > 0 {
            out.push(' ');
        }
        out.push_str(&format!("{:^3}", column + 1));
    }
    out.push_str("   column number");
    out
}

/// The serialized game half of a prompt request.
///
/// Field names match the core `GameRequest` exactly. That is deliberate: the JSON block in the
/// system prompt documents these names, so a divergence between this struct and the prompt text would
/// be a prompt that describes fields the payload does not contain.
#[derive(Serialize)]
pub struct PromptGameRequest<'a> {
    game: GameKind,
    you_are: GameSide,
    board: &'a GameBoard,
    /// The same board, drawn. See the module header for why this is carried alongside the JSON.
    board_text: String,
    legal_moves: Vec<String>,
    history: Vec<String>,
    ply: u32,
    remaining_plies: u32,
    last_move: Option<String>,
}

/// The serialized user message for a game request.
#[derive(Serialize)]
pub struct GamePromptRequest<'a> {
    /// The identifier for this match, for the model's own cross-referencing.
    pub match_id: &'a str,
    /// The board state to decide from.
    pub game: PromptGameRequest<'a>,
}

/// Builds the user-message payload for a game request.
pub fn prompt_request<'a>(match_id: &'a str, game: &'a GameRequest) -> GamePromptRequest<'a> {
    GamePromptRequest {
        match_id,
        game: PromptGameRequest {
            game: game.kind,
            you_are: game.side,
            board: &game.board,
            board_text: render_board(&game.board),
            legal_moves: game
                .legal_moves
                .iter()
                .map(|candidate| protocol_move_name(game.kind, move_index(candidate)))
                .collect(),
            history: game
                .history
                .iter()
                .map(|past| protocol_move_name(game.kind, move_index(past)))
                .collect(),
            ply: game.ply,
            remaining_plies: game.remaining_plies,
            last_move: game
                .last_move
                .map(|last| protocol_move_name(game.kind, move_index(&last))),
        },
    }
}

/// The board index a move names, across every game this module renders.
fn move_index(move_: &GameMove) -> usize {
    match move_ {
        GameMove::TicTacToe(index) | GameMove::ConnectFour(index) => *index,
        GameMove::Rps(choice) => match choice {
            probelab_core::RpsChoice::Rock => 0,
            probelab_core::RpsChoice::Paper => 1,
            probelab_core::RpsChoice::Scissors => 2,
        },
        GameMove::Battleship(position) => usize::from(position.x),
    }
}

/// Parses one model response into a legal game move.
///
/// `legal_moves` is the request's own list, and the returned move is guaranteed to be in it. The
/// parse therefore cannot widen the vocabulary, and a model that invented a move is refused with
/// [`ActionProtocolError::OutOfVocabulary`] rather than being handed to the engine to refuse.
pub fn parse_game_move_response(
    raw: &str,
    kind: GameKind,
    legal_moves: &[GameMove],
) -> Result<GameMove, ActionProtocolError> {
    let object = single_move_object(raw.trim())?.ok_or(ActionProtocolError::Malformed)?;
    let legal = game_move_vocabulary(kind, legal_moves);
    let normalized = object.move_.to_ascii_uppercase();
    let candidate = legal
        .iter()
        .find(|(_, canonical)| canonical.eq_ignore_ascii_case(&normalized))
        .map(|(move_, _)| *move_)
        // A bare number is accepted for connect four, because `{"move":"3"}` is a natural thing for
        // a small model to emit and refusing it would measure JSON formatting rather than play.
        .or_else(|| bare_index(kind, legal_moves, &normalized));
    let Some(candidate) = candidate else {
        // Distinguish "not a move this game has" from "a move this game has, but not right now".
        // The first is a protocol error the model can fix by reading the vocabulary; the second is a
        // rules mistake, which is a real measurement.
        return Err(if has_prefix(&normalized, kind) {
            ActionProtocolError::OutOfVocabulary
        } else {
            ActionProtocolError::UnknownAction
        });
    };
    Ok(candidate)
}

/// Whether a name is shaped like a move for this game, regardless of whether it is currently legal.
fn has_prefix(name: &str, kind: GameKind) -> bool {
    match kind {
        GameKind::TicTacToe => name.starts_with("CELL_"),
        GameKind::ConnectFour => name.starts_with("COLUMN_"),
        GameKind::Rps => name.starts_with("PLAY_"),
        GameKind::Battleship => name.starts_with("TARGET_"),
    }
}

fn bare_index(kind: GameKind, legal_moves: &[GameMove], normalized: &str) -> Option<GameMove> {
    let Ok(one_based) = normalized.parse::<usize>() else {
        return None;
    };
    if one_based == 0 {
        return None;
    }
    let zero_based = one_based - 1;
    legal_moves.iter().copied().find(|candidate| {
        matches!(
            (candidate, kind),
            (GameMove::TicTacToe(index), GameKind::TicTacToe)
                | (GameMove::ConnectFour(index), GameKind::ConnectFour)
                if *index == zero_based
        )
    })
}

/// Every legal move of this kind paired with the canonical name a model would write.
fn game_move_vocabulary(kind: GameKind, legal_moves: &[GameMove]) -> Vec<(GameMove, String)> {
    legal_moves
        .iter()
        .map(|candidate| (*candidate, protocol_move_name(kind, move_index(candidate))))
        .collect()
}

#[derive(serde::Deserialize)]
#[serde(deny_unknown_fields)]
struct MoveObject {
    #[serde(rename = "move")]
    move_: String,
}

/// Extracts the single move object from a response.
///
/// The tolerance rules are the grid parser's, unchanged and for the same reason: sharing them is what
/// makes "the model spoke the protocol" mean one thing across every task in the lab.
fn single_move_object(trimmed: &str) -> Result<Option<MoveObject>, ActionProtocolError> {
    if trimmed.is_empty() {
        return Err(ActionProtocolError::Empty);
    }
    if trimmed.starts_with('[') {
        return Err(ActionProtocolError::Array);
    }
    let Some(start) = trimmed.find('{') else {
        return Err(ActionProtocolError::Malformed);
    };
    let Some(end) = json_object_end(trimmed, start) else {
        return Err(ActionProtocolError::Malformed);
    };
    let suffix = trimmed[end + 1..].trim();
    if has_structured_json_prefix(suffix) {
        return Err(ActionProtocolError::MultipleValues);
    }
    let object = serde_json::from_str::<MoveObject>(&trimmed[start..=end]).map_err(|error| {
        let message = error.to_string();
        if message.contains("missing field `move`") {
            ActionProtocolError::MissingAction
        } else if message.contains("unknown field") {
            ActionProtocolError::UnknownField
        } else {
            ActionProtocolError::Malformed
        }
    })?;
    Ok(Some(object))
}

fn json_object_end(input: &str, start: usize) -> Option<usize> {
    let bytes = input.as_bytes();
    let mut depth = 0usize;
    let mut in_string = false;
    let mut escaped = false;
    for (index, byte) in bytes.iter().enumerate().skip(start) {
        let byte = *byte;
        if in_string {
            if escaped {
                escaped = false;
            } else if byte == b'\\' {
                escaped = true;
            } else if byte == b'"' {
                in_string = false;
            }
            continue;
        }
        match byte {
            b'"' => in_string = true,
            b'{' => depth += 1,
            b'}' => {
                depth = depth.checked_sub(1)?;
                if depth == 0 {
                    return Some(index);
                }
            }
            _ => {}
        }
    }
    None
}

fn has_structured_json_prefix(input: &str) -> bool {
    let input = input.trim_start();
    input.contains('{')
        || input.contains('[')
        || input.starts_with('"')
        || input.starts_with('-')
        || input.starts_with(|character: char| character.is_ascii_digit())
        || input.starts_with("true")
        || input.starts_with("false")
        || input.starts_with("null")
}

