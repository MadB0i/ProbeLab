#[cfg(test)]
mod tests {
    use super::*;
    use probelab_core::{ConnectFourCell, TicTacToeCell};

    #[test]
    fn a_tic_tac_toe_prompt_carries_the_board_twice_and_no_hidden_state() {
        let request = GameRequest {
            kind: GameKind::TicTacToe,
            side: GameSide::Second,
            board: GameBoard::TicTacToe {
                cells: vec![
                    TicTacToeCell::First,
                    TicTacToeCell::Empty,
                    TicTacToeCell::Empty,
                    TicTacToeCell::Second,
                    TicTacToeCell::Empty,
                    TicTacToeCell::Empty,
                    TicTacToeCell::Empty,
                    TicTacToeCell::Empty,
                    TicTacToeCell::Empty,
                ],
            },
            legal_moves: vec![GameMove::TicTacToe(1), GameMove::TicTacToe(2)],
            history: vec![GameMove::TicTacToe(0)],
            ply: 2,
            remaining_plies: 8,
            last_move: Some(GameMove::TicTacToe(3)),
        };
        let payload = serde_json::to_string(&prompt_request("m1", &request)).expect("serializable");
        assert!(payload.contains("CELL_2"), "{payload}");
        assert!(payload.contains("CELL_1"), "history renders: {payload}");
        assert!(payload.contains("\"you_are\":\"second\""), "{payload}");
        assert!(
            payload.contains("row 1") && payload.contains("row 3"),
            "the drawn board must have all three rows: {payload}"
        );
    }

    #[test]
    fn a_connect_four_board_renders_bottom_row_first_from_a_column_major_store() {
        // Cells are column-major: index = column * rows + row. Column 0 has a disc on row 0 only.
        let cells = vec![
            ConnectFourCell::First,
            ConnectFourCell::Empty,
            ConnectFourCell::Empty,
            ConnectFourCell::Empty,
            ConnectFourCell::Empty,
            ConnectFourCell::Empty,
        ];
        let drawn = render_board(&GameBoard::ConnectFour {
            columns: 2,
            rows: 3,
            cells,
        });
        let lines: Vec<&str> = drawn.lines().collect();
        // Three cell rows, then the column-number footer.
        assert_eq!(lines.len(), 4, "{drawn}");
        assert!(lines[0].contains(". "), "top row is empty: {drawn}");
        assert!(lines[1].contains(". "), "middle row is empty: {drawn}");
        assert!(
            lines[2].starts_with("   O "),
            "the bottom-left cell is the First side's disc: {drawn}"
        );
        assert!(
            lines[3].contains("1"),
            "column numbers are labelled: {drawn}"
        );
    }

    #[test]
    fn a_legal_column_name_parses_back_to_that_column() {
        let legal = vec![GameMove::ConnectFour(0), GameMove::ConnectFour(3)];
        let parsed =
            parse_game_move_response(r#"{"move":"COLUMN_4"}"#, GameKind::ConnectFour, &legal)
                .expect("legal move");
        assert_eq!(parsed, GameMove::ConnectFour(3));
    }

    #[test]
    fn a_one_based_cell_name_maps_to_a_zero_based_index() {
        let legal = vec![GameMove::TicTacToe(4)];
        let parsed = parse_game_move_response(r#"{"move":"CELL_5"}"#, GameKind::TicTacToe, &legal)
            .expect("legal move");
        assert_eq!(parsed, GameMove::TicTacToe(4));
    }

    #[test]
    fn a_full_column_is_refused_as_out_of_vocabulary_not_as_an_unknown_action() {
        let legal = vec![GameMove::ConnectFour(2)];
        assert_eq!(
            parse_game_move_response(r#"{"move":"COLUMN_6"}"#, GameKind::ConnectFour, &legal),
            Err(ActionProtocolError::OutOfVocabulary)
        );
        assert_eq!(
            parse_game_move_response(r#"{"move":"ROCK"}"#, GameKind::ConnectFour, &legal),
            Err(ActionProtocolError::UnknownAction)
        );
    }

    #[test]
    fn fenced_and_prose_wrapped_replies_are_tolerated_and_a_second_object_is_not() {
        let legal = vec![GameMove::ConnectFour(1)];
        let fenced = "Sure!\n```json\n{\"move\":\"COLUMN_2\"}\n```\nThanks.";
        assert_eq!(
            parse_game_move_response(fenced, GameKind::ConnectFour, &legal),
            Ok(GameMove::ConnectFour(1))
        );
        assert_eq!(
            parse_game_move_response(
                "{\"move\":\"COLUMN_2\"}\n{\"move\":\"COLUMN_3\"}",
                GameKind::ConnectFour,
                &legal
            ),
            Err(ActionProtocolError::MultipleValues)
        );
    }

    #[test]
    fn an_unknown_field_is_refused_so_a_reasoning_cannot_slip_in() {
        let legal = vec![GameMove::ConnectFour(1)];
        assert_eq!(
            parse_game_move_response(
                r#"{"move":"COLUMN_2","reason":"because"}"#,
                GameKind::ConnectFour,
                &legal
            ),
            Err(ActionProtocolError::UnknownField)
        );
    }

    #[test]
    fn each_game_has_a_distinct_versioned_prompt() {
        let (tic_prompt, tic_version) = prompt_for(GameKind::TicTacToe);
        let (connect_prompt, connect_version) = prompt_for(GameKind::ConnectFour);
        assert_ne!(tic_version, connect_version);
        assert!(tic_prompt.contains("tic-tac-toe") || tic_prompt.contains("Tic-Tac-Toe"));
        assert!(connect_prompt.contains("connect four") || connect_prompt.contains("Connect Four"));
        assert!(
            tic_prompt.contains("CELL_1"),
            "the prompt documents the vocabulary"
        );
        assert!(
            connect_prompt.contains("COLUMN_1"),
            "the prompt documents the vocabulary"
        );
    }
}
